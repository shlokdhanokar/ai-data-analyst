"""LLM client abstraction.

`OpenAICompatibleClient` speaks the OpenAI Chat Completions protocol, which Groq, OpenAI,
Together, Ollama and vLLM all implement, so switching provider is a config change.
Responses are streamed; text tokens are forwarded to an optional callback while tool-call
deltas are accumulated.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Callable, Protocol

from .logging_setup import get_logger, timed

logger = get_logger("llm")

TokenCallback = Callable[[str], None]


@dataclass
class ToolCall:
    id: str
    name: str
    arguments: str


@dataclass
class LLMResponse:
    content: str
    tool_calls: list[ToolCall] = field(default_factory=list)
    usage: dict[str, int] = field(default_factory=dict)

    def assistant_message(self) -> dict[str, Any]:
        msg: dict[str, Any] = {"role": "assistant", "content": self.content or ""}
        if self.tool_calls:
            msg["tool_calls"] = [
                {"id": tc.id, "type": "function", "function": {"name": tc.name, "arguments": tc.arguments}}
                for tc in self.tool_calls
            ]
        return msg


class LLMError(RuntimeError):
    """Raised for unrecoverable LLM failures (auth, quota, network after retries)."""


class ToolFormatError(LLMError):
    """The provider rejected a malformed tool call generated by the model (retryable)."""


class LLMClient(Protocol):
    model: str

    def complete(self, messages: list[dict[str, Any]], tools: list[dict[str, Any]] | None = None,
                 on_token: TokenCallback | None = None) -> LLMResponse: ...


class OpenAICompatibleClient:
    def __init__(self, api_key: str, base_url: str, model: str, temperature: float = 0.1,
                 timeout: float = 60.0, max_retries: int = 3) -> None:
        from openai import OpenAI

        if not api_key:
            raise LLMError("No API key configured. Set GROQ_API_KEY (or LLM_API_KEY) in .env.")
        self.model = model
        self.temperature = temperature
        self._client = OpenAI(api_key=api_key, base_url=base_url, timeout=timeout, max_retries=max_retries)

    def complete(self, messages: list[dict[str, Any]], tools: list[dict[str, Any]] | None = None,
                 on_token: TokenCallback | None = None) -> LLMResponse:
        import openai

        kwargs: dict[str, Any] = dict(model=self.model, messages=messages, temperature=self.temperature, stream=True)
        if tools:
            kwargs.update(tools=tools, tool_choice="auto", parallel_tool_calls=True)

        with timed(logger, "llm_call", model=self.model, n_messages=len(messages), tools=bool(tools)) as log:
            try:
                stream = self._client.chat.completions.create(**kwargs)
                response = self._consume(stream, on_token)
            except openai.BadRequestError as exc:
                body = str(exc)
                markers = ("tool_use_failed", "failed_generation", "tool call validation", "parse tool call")
                if any(m in body for m in markers):
                    raise ToolFormatError(body[:500]) from exc
                raise LLMError(f"Request rejected by the LLM provider: {body[:300]}") from exc
            except openai.AuthenticationError as exc:
                raise LLMError("LLM authentication failed - check your API key.") from exc
            except openai.RateLimitError as exc:
                raise LLMError("LLM rate limit reached - please wait a moment and retry.") from exc
            except (openai.APIConnectionError, openai.APITimeoutError) as exc:
                raise LLMError("Could not reach the LLM provider (network/timeout).") from exc
            except openai.APIError as exc:
                raise LLMError(f"LLM provider error: {exc}") from exc
            log.update(response.usage, n_tool_calls=len(response.tool_calls))
            return response

    @staticmethod
    def _consume(stream: Any, on_token: TokenCallback | None) -> LLMResponse:
        content: list[str] = []
        calls: dict[int, dict[str, str]] = {}
        usage: dict[str, int] = {}
        for chunk in stream:
            u = getattr(chunk, "usage", None) or getattr(getattr(chunk, "x_groq", None), "usage", None)
            if u:
                usage = {"prompt_tokens": u.prompt_tokens, "completion_tokens": u.completion_tokens,
                         "total_tokens": u.total_tokens}
            if not chunk.choices:
                continue
            delta = chunk.choices[0].delta
            if delta.content:
                content.append(delta.content)
                if on_token:
                    on_token(delta.content)
            for tc in delta.tool_calls or []:
                slot = calls.setdefault(tc.index, {"id": "", "name": "", "arguments": ""})
                if tc.id:
                    slot["id"] = tc.id
                if tc.function and tc.function.name:
                    slot["name"] += tc.function.name
                if tc.function and tc.function.arguments:
                    slot["arguments"] += tc.function.arguments
        tool_calls = [
            ToolCall(id=c["id"] or f"call_{i}", name=c["name"], arguments=c["arguments"] or "{}")
            for i, c in sorted(calls.items())
        ]
        return LLMResponse(content="".join(content), tool_calls=tool_calls, usage=usage)


def parse_args(raw: str) -> dict[str, Any]:
    try:
        value = json.loads(raw or "{}")
        return value if isinstance(value, dict) else {}
    except json.JSONDecodeError:
        return {}
